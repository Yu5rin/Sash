/** 比べる前の正規化：全角半角をそろえ、小文字にし、ひらがなをカタカナにする（「ふぉるだー」でもフォルダーに当たるように）。 */
export function normalize(text: string): string {
  return text
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60))
    .trim();
}

/** 長音の有無の揺れ（フォルダ / フォルダー、ユーザ / ユーザー）を吸収する。 */
function stripLong(text: string): string {
  return text.replace(/ー/g, '');
}

const normalizedJa: readonly { key: string; terms: readonly string[] }[] = Object.entries(JA_KEYWORDS).map(([k, v]) => ({ key: stripLong(normalize(k)), terms: v }));

/** 日本語の語を、アイコン名の英単語（の並び）に置き換える。見つからなければ空。 */
export function jaToEnglish(token: string): string[] {
  const t = stripLong(normalize(token));
  if (!t) return [];
  const out = new Set<string>();
  for (const { key, terms } of normalizedJa) {
    // 入力の途中（「フォル」）と、言い回しの付いたもの（「保存する」）の両方で当たるようにする。
    // 1文字の語（上・下・表など）は、入力と完全に一致したときだけ使う（「上書き」で「上」が当たらないように）
    const hit = key === t || (t.length >= 2 && key.startsWith(t)) || (key.length >= 2 && t.startsWith(key));
    if (hit) for (const term of terms) out.add(term);
  }
  return [...out];
}

/**
 * 文（ボタンのラベルなど）の中に含まれる日本語の言葉を辞書から探し、英単語（の並び）にする。文の中で先に出てくる言葉を先に返す。
 * ラベルは「集計する」「CSV出力」のように言葉が空白で区切られていないので、jaToEnglish（語の単位で引く）ではなく、
 * 辞書の言葉が文に含まれるかで探す。1文字の言葉（上・表など）は、文そのものと一致したときだけ使う（「上書き」で「上」が当たらないように）。
 */
export function jaTermsInText(text: string): string[] {
  const t = stripLong(normalize(text));
  if (!t) return [];
  const hits: { at: number; len: number; terms: readonly string[] }[] = [];
  for (const { key, terms } of normalizedJa) {
    if (!key) continue;
    const at = key.length >= 2 ? t.indexOf(key) : key === t ? 0 : -1;
    if (at >= 0) hits.push({ at, len: key.length, terms });
  }
  // 先に出てくる言葉、同じ位置なら長い言葉（「フォルダを開く」の「フォルダ」より「フォルダを開く」）を先にする
  hits.sort((a, b) => a.at - b.at || b.len - a.len);
  const out: string[] = [];
  for (const h of hits) for (const term of h.terms) if (!out.includes(term)) out.push(term);
  return out;
}

